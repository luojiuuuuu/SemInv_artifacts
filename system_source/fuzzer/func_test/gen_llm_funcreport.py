def _selector_of(name: str, sig_map: Dict[str,str]) -> str:
    # sig_map: {selector: "func(argtypes)"}
    for sel, sig in sig_map.items():
        if sig.split("(")[0] == name:
            return sel.replace("0x","")
    return None

def heuristic_seeds(contract: str, abi: List[dict], sig_map: Dict[str,str],
                    standards: List[str]) -> Dict[str, Any]:
    """无 LLM 兜底启发：给出 2–3 条多步序列（可立即用）。"""
    seeds = []
    # ERC20 典型多步：mint -> approve -> transferFrom
    if "ERC20" in standards:
        sel_mint = _selector_of("mint", sig_map) or "40c10f19"
        sel_approve = _selector_of("approve", sig_map) or "095ea7b3"
        sel_tf = _selector_of("transferFrom", sig_map) or "23b872dd"
        seeds.append({
            "id": "seed-erc20-approve-xferFrom",
            "label_guess": ["AllowancePath","Transfer","balance[dst]++","balance[src]--"],
            "sequence": [
                {"from":"$OWNER","to":"$DEPLOYED","value":"0","selector":sel_mint,"args":["0xA11CE","1000"]},
                {"from":"0xA11CE","to":"$DEPLOYED","value":"0","selector":sel_approve,"args":["0xB0B","700"]},
                {"from":"0xB0B","to":"$DEPLOYED","value":"0","selector":sel_tf,"args":["0xA11CE","0xB0B","600"]}
            ]
        })
    # 通用：为任意一个非 view/pure 的 external/public 生成 2 步链
    for item in abi:
        if item.get("type")!="function": continue
        if item.get("stateMutability") in ("view","pure"): continue
        name = item["name"]
        sel = _selector_of(name, sig_map)
        if not sel: continue
        arg_vals = []
        for inp in item.get("inputs", []):
            t = inp["type"]
            if t.startswith("uint"): arg_vals.append("1")
            elif t=="address": arg_vals.append("0xB0B")
            elif t=="bool": arg_vals.append("true")
            else: arg_vals.append("0")
        seeds.append({
            "id": f"seed-{name}-basic",
            "label_guess": [f"MayTouch({name})"],
            "sequence": [
                {"from":"$OWNER","to":"$DEPLOYED","value":"0","selector":sel,"args":arg_vals}
            ]
        })
        if len(seeds) >= 3: break

    return {
        "meta": {"contract_name": contract, "version": "1.0.0"},
        "seeds": seeds
    }

def call_llm(prompt: str, api_key: str, api_url: str = "https://api.openai.com/v1/chat/completions",
             model: str = "gpt-4.1") -> str:
    """
    调用 LLM 接口，返回模型输出文本。
    - prompt: 传入的文本
    - api_key: 你的 OpenAI API Key（外部传入，不写死）
    - api_url: LLM 接口地址（默认 OpenAI，可替换成你自己的）
    - model: 使用的模型名称
    """
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    body = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "temperature": 0.3
    }
    resp = requests.post(api_url, headers=headers, json=body, timeout=60)
    resp.raise_for_status()
    data = resp.json()
    return data["choices"][0]["message"]["content"].strip()


# Active functional-report LLM entrypoint below is English-only. Legacy non-English prompt entrypoint was replaced during prompt normalization.

def llm_generate_report_and_seeds(contract: str,
                                  abi: List[dict],
                                  sig_map: Dict[str, str],
                                  standards: List[str],
                                  api_key: str,
                                  api_url: str,
                                  model: str,
                                  source_code_text: str = "",
                                  foundry_test_src: str = "",
                                  foundry_json: Dict[str, Any] = None,
                                  prefer_lang: str = "en") -> Dict[str, Any]:
    """Generate an English functional-test report with the LLM.

    Seeds are intentionally not generated by this LLM prompt; the surrounding
    pipeline derives seeds from successful Foundry executions or local
    heuristics. The signature is kept compatible with the previous function.
    """
    abi_str = json.dumps(abi, indent=2, ensure_ascii=False)
    sig_map_str = json.dumps(sig_map, indent=2, ensure_ascii=False)
    standards_str = ", ".join(standards)
    foundry_json_str = json.dumps(foundry_json or {}, indent=2, ensure_ascii=False)

    prompt = f"""
You are a smart-contract security testing and audit expert. Write in English.

Goal:
Generate a functional test report based on the contract source, the generated Foundry test code, and the current Foundry JSON results. The report must cover functional points, key execution paths, and exceptional or revert paths. Base every claim on evidence from the provided material; do not speculate beyond it.

Contract name:
{contract}

Reference standards or traits, if any:
{standards_str}

ABI, for cross-checking:
{abi_str}

Function selector map, selector -> signature, for cross-checking:
{sig_map_str}

Contract source, excerpt or full text:
{source_code_text}

Foundry test code, excerpt or full text:
{foundry_test_src}

Foundry test JSON results, excerpt or full text:
```json
{foundry_json_str}
```

Writing requirements:
1. Start with a 3 to 5 sentence overview describing which main workflows are covered, such as mint, approve, transfer, transferFrom, ownership, lifecycle, or state transitions when applicable.
2. List the key functional test points and their evidence. Cite concrete function names, generated test names, assertions, revert expectations, or result fields from the source/test/results. Avoid unsupported claims.
3. Include exceptional paths and boundary paths when they are present in the evidence.
4. When useful, organize observations under the six semantic invariant families: Financial & Accounting, Authorization & Access Control, Protocol State Machine, Transactional Consistency, Resource & Execution Integrity, and External Interaction & Environment.
5. End with a 3 to 5 sentence summary of the contract's tested behavior and purpose.
6. Keep the report concise, approximately 300 to 500 words.

Forbidden output:
- Do not generate seeds.
- Do not output JSON.
- Do not use markdown code fences except where they already appear in the input above.
- Output plain English report text only.
""".strip()

    report = sanitize_report_text(call_llm(prompt, api_key=api_key, api_url=api_url, model=model))
    return {"report": report}


